local M = {}

local function style(spec)
  local attrs = {}
  for _, attr in ipairs(spec or {}) do
    attrs[attr] = true
  end
  return attrs
end

local function hl(fg, bg, spec)
  local value = style(spec)
  value.fg = fg
  value.bg = bg
  return value
end

local function link(group)
  return { link = group }
end

